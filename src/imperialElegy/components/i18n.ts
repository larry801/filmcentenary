/** The English dictionary defines the shape both locales must share. */
export type IEStrings = typeof S.en;
export const ieStringsFor = (locale: IELocale): IEStrings => S[locale];
export const ieT = (): IEStrings => ieStringsFor(ieLocale());
export const ieString = (key: string): string => {
  const dict: any = S[ieLocale()];
  return key.split(".").reduce((acc, part) => (acc == null ? undefined : acc[part]), dict) ?? key;
};
