const entryFor = (n: number): Decade => {
  if (n <= 70) return "1850s";
  if (n <= 81) return "1870s";
  if (n <= 91) return "1880s";
  if (n <= 99) return "1890s";
  return "1900s";
};

const A = (
  number: number,
  cp: number,
  type: CardDef["type"],
  title: string,
  titleZh: string,
  text: string,
  textZh: string,
  effects: Effect[],
  extra: Partial<CardDef> = {},
): CardDef => ({
  id: cardIdForAction(number),
  number,
  kind: "action",
  cp,
  entry: extra.entry ?? entryFor(number),
  type,
  title,
  titleZh,
  text,
  textZh,
  effects,
  image: `cards/action-${String(number).padStart(3, "0")}.jpg`,
  ...extra,
});

