export const CARD_BY_NUMBER: Record<number, OfficialCardDef> = Object.fromEntries(
    OFFICIAL_CARDS.map((c) => [c.number, c]),
);

export const CARD_BY_ID: Record<string, OfficialCardDef> = Object.fromEntries(
    OFFICIAL_CARDS.map((c) => [c.id, c]),
);

export const cardByNumber = (n: number): OfficialCardDef | undefined => CARD_BY_NUMBER[n];

export const HOME_CARDS = OFFICIAL_CARDS.filter((c) => c.kind === "home");

export const MANDATORY_CARDS = OFFICIAL_CARDS.filter((c) => c.kind === "mandatory");

export const cardsInRange = (from: number, to: number): OfficialCardDef[] =>
    OFFICIAL_CARDS.filter((c) => c.number >= from && c.number <= to);

export const cpCoverage = (): CardCpCoverage => {
    const missingNumbers = OFFICIAL_CARDS.filter((c) => c.cp === null).map((c) => c.number);
    return {
        total: OFFICIAL_CARDS.length,
        known: OFFICIAL_CARDS.length - missingNumbers.length,
        missing: missingNumbers.length,
        missingNumbers,
    };
};
